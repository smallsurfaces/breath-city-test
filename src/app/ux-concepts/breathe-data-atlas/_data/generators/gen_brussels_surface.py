#!/usr/bin/env python3
"""Generate the MOCK BelAQI surface for the Breathe Data Atlas Brussels page (SPEC ADDENDUM,
Brussels: "a mock BelAQI surface shaded across the Brussels-Capital Region, as if relayed from
IRCELINE's interpolated hourly layer").

Output: _data/areas/brussels-surface.json

THIS IS SAMPLE DATA standing in for the city's own model output (IRCELINE's interpolated hourly
BelAQI). It is NOT computed from any reading, and the page never computes it either: the page only
draws the grid's bands and looks up the band of the cell a point falls in. A real build relays
IRCELINE's own layer.

Shape: a regular grid over the region's bounding box; each cell carries one BelAQI level
(1 Excellent ... 10 Horrible) or 0 outside the region (cell centre outside the OSM outline in
_data/boundaries/brussels.json). Mostly 3 "Good" and 4 "Fairly good", from a smooth invented field,
with 5 "Moderate" along a few major roads (approximate lines: the inner ring, the E40 east, the A12
north, the Boulevard Leopold III and the Chaussée de Mons), so the method reads at a glance.

Usage: python3 _data/generators/gen_brussels_surface.py
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.dirname(HERE)

CELL_LNG = 0.002     # about 140 m at 50.85 N
CELL_LAT = 0.00125   # about 139 m

boundary = json.load(open(os.path.join(DATA, 'boundaries', 'brussels.json')))
ring = boundary['rings'][0]
west, south, east, north = boundary['bbox']


def inside(x, y):
    hit = False
    for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            hit = not hit
    return hit


# Approximate major-road polylines, [lng, lat] (by eye; only shapes the mock).
ROADS = [
    # Inner ring (petite ceinture), as a loop around the centre
    [(4.3437, 50.8510), (4.3500, 50.8590), (4.3640, 50.8600), (4.3720, 50.8530), (4.3700, 50.8410),
     (4.3570, 50.8360), (4.3440, 50.8420), (4.3437, 50.8510)],
    # E40 east towards Leuven
    [(4.3900, 50.8560), (4.4200, 50.8600), (4.4500, 50.8680), (4.4800, 50.8720)],
    # A12 north
    [(4.3520, 50.8650), (4.3560, 50.8850), (4.3620, 50.9100)],
    # Boulevard Leopold III / NATO
    [(4.3800, 50.8650), (4.4100, 50.8750), (4.4350, 50.8800)],
    # Chaussée de Mons south-west
    [(4.3400, 50.8420), (4.3100, 50.8330), (4.2700, 50.8230)],
]
ROAD_KM = 0.35


def km(a, b):
    dx = (a[0] - b[0]) * 111.32 * math.cos(math.radians(50.85))
    dy = (a[1] - b[1]) * 110.57
    return math.hypot(dx, dy)


def seg_km(p, a, b):
    ax, ay = a
    bx, by = b
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((p[0] - ax) * dx + (p[1] - ay) * dy) / (dx * dx + dy * dy)))
    return km(p, (ax + t * dx, ay + t * dy))


def near_road(p):
    return any(seg_km(p, a, b) < ROAD_KM for line in ROADS for a, b in zip(line, line[1:]))


def field(x, y):
    """A smooth invented field: higher towards the centre and the canal, lower in the south-east
    (Sonian forest edge). Thresholded into Good (3) and Fairly good (4)."""
    centre = math.exp(-(km((x, y), (4.355, 50.850)) / 4.0) ** 2)
    canal = math.exp(-(km((x, y), (4.330, 50.865)) / 3.0) ** 2)
    wave = 0.12 * math.sin(x * 140) * math.cos(y * 160)
    forest = math.exp(-(km((x, y), (4.43, 50.79)) / 3.5) ** 2)
    return centre * 0.55 + canal * 0.35 + wave - forest * 0.35


cols = int(math.ceil((east - west) / CELL_LNG))
rows = int(math.ceil((north - south) / CELL_LAT))
grid = []
counts = {}
for r in range(rows):
    lat = north - (r + 0.5) * CELL_LAT
    line = ''
    for c in range(cols):
        lng = west + (c + 0.5) * CELL_LNG
        if not inside(lng, lat):
            band = 0
        elif near_road((lng, lat)):
            band = 5
        else:
            band = 4 if field(lng, lat) > 0.32 else 3
        counts[band] = counts.get(band, 0) + 1
        line += 'A' if band == 10 else str(band)
    grid.append(line)

payload = {
    '_note': ('MOCK BelAQI surface for the Breathe Data Atlas Brussels page: sample data standing in for '
              "IRCELINE's interpolated hourly BelAQI layer. Not computed from readings. Each row is north to "
              'south, each character a cell west to east: 0 = outside the region, 1 to 9 = BelAQI level, '
              'A = 10. Generated by _data/generators/gen_brussels_surface.py. Regenerate, do not hand-edit.'),
    'city': 'brussels',
    'indexName': 'BelAQI',
    'west': west, 'north': north, 'cellLng': CELL_LNG, 'cellLat': CELL_LAT,
    'cols': cols, 'rows': rows,
    'grid': grid,
}
out = os.path.join(DATA, 'areas', 'brussels-surface.json')
with open(out, 'w') as fh:
    json.dump(payload, fh, separators=(',', ':'))
    fh.write('\n')
print('wrote', cols, 'x', rows, 'cells', counts, os.path.getsize(out), 'bytes')
